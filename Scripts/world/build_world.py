"""Builds Lvl_HiddenLeafValley, the open world (sub-project #3), from Scripts/world/world_layout.json.

Run through Scripts/run_python.ps1 (UE Python commandlet; close the GUI editor first). The stage is picked by the
environment variable SHINOBI_WORLD_STAGE (default "terrain"); later stages load the existing map and add to it.

  terrain   new World Partition map; M_Landscape; the landscape from SourceArt/World/Terrain (generated by
            make_heightmap.py, which this stage runs first with system Python if the maps are missing); sun, sky,
            fog, clouds, the toon post volume; PlayerStart in the village; river water plane; edge walls.
  dress     everything in placements.json (make_placements.py, run first with system Python): village buildings, wall
            ring and gate, bridge, camp and boss dressing, camp/boss markers (TargetPoints tagged ShinobiCampSite,
            Camp:<id>, Difficulty:<n>, Boss), and the nature scatter as one AShinobiScatterActor per 128 m chunk.
            Re-running replaces the previous dressing (every actor it spawns carries the tag ShinobiDressing).
  mood      the warm late-afternoon sun and valley fog (also applied by terrain), and the ambient sounds from
            SourceArt/Audio/World (make_ambience.py, run first): the forest bed everywhere, the river along its course.
            Re-running replaces the previous sounds (tag ShinobiMood).
"""
