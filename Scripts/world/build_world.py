def log(message):
    unreal.log(f"[build_world] {message}")


def uu(metres):
    return metres * 100.0


def ensure_dir(path):
    if not unreal.EditorAssetLibrary.does_directory_exist(path):
        unreal.EditorAssetLibrary.make_directory(path)


def fresh_asset(name, directory, cls, factory):
    path = f"{directory}/{name}"
    if unreal.EditorAssetLibrary.does_asset_exist(path):
        unreal.EditorAssetLibrary.delete_asset(path)
    asset = TOOLS.create_asset(name, directory, cls, factory)
    if asset is None:
        raise RuntimeError(f"could not create {path}")
    return asset


def terrain_maps(regenerate=False):
    meta_path = os.path.join(TERRAIN_DIR, "terrain.json")
    if regenerate or not os.path.exists(meta_path):
        subprocess.run(["python", os.path.join(HERE, "make_heightmap.py"), TERRAIN_DIR], check=True)
    with open(meta_path, encoding="utf-8") as f:
        return json.load(f)


def expr(m, cls, x, y, **props):
    node = MEL.create_material_expression(m, cls, x, y)
    for key, value in props.items():
        node.set_editor_property(key, value)
    return node


def sample(m, texture_id, suffix, uv, x, y):
    kind = {"A": unreal.MaterialSamplerType.SAMPLERTYPE_COLOR, "N": unreal.MaterialSamplerType.SAMPLERTYPE_NORMAL}.get(
        suffix, unreal.MaterialSamplerType.SAMPLERTYPE_MASKS)
    node = expr(m, unreal.MaterialExpressionTextureSample, x, y, sampler_type=kind,
                sampler_source=unreal.SamplerSourceMode.SSM_WRAP_WORLD_GROUP_SETTINGS,
                texture=unreal.load_asset(f"{TEXTURES}/{texture_id}/T_{texture_id}_{suffix}"))
    MEL.connect_material_expressions(uv, "", node, "UVs")
    return node


def layer_blend(m, x, y):
    blend = expr(m, unreal.MaterialExpressionLandscapeLayerBlend, x, y)
    layers = []
    for name in LAYERS:
        entry = unreal.LayerBlendInput()
        entry.set_editor_property("layer_name", name)
        entry.set_editor_property("blend_type", unreal.LandscapeLayerBlendType.LB_HEIGHT_BLEND)
        entry.set_editor_property("preview_weight", 1.0 if name == "Grass" else 0.0)
        layers.append(entry)
    blend.set_editor_property("layers", layers)
    return blend


def grass_types():
    """LGT_<type> assets from GRASS_TYPES and the PH_Grass / PH_Shrub catalog variants."""
    ensure_dir(GRASS_DIR)
    with open(os.path.join(HERE, "library_catalog.json"), encoding="utf-8") as f:
        catalog = json.load(f)
    plants = {**catalog.get("PH_Grass", {}), **catalog.get("PH_Shrub", {})}
    out = {}
    for type_name, (_, varieties) in GRASS_TYPES.items():
        path = f"{GRASS_DIR}/LGT_{type_name}"
        lgt = unreal.load_asset(path) if unreal.EditorAssetLibrary.does_asset_exist(path) else TOOLS.create_asset(
            f"LGT_{type_name}", GRASS_DIR, unreal.LandscapeGrassType, None)
        entries = []
        for prefix, density, count in varieties:
            for name in sorted(n for n in plants if n.startswith(prefix))[:count]:
                v = unreal.GrassVariety()
                v.set_editor_property("grass_mesh", unreal.load_asset(plants[name]["mesh"]))
                per = unreal.PerPlatformFloat()
                per.set_editor_property("default", float(density))
                v.set_editor_property("grass_density", per)
                start, end = unreal.PerPlatformInt(), unreal.PerPlatformInt()
                near_fade = type_name == "Meadow"
                start.set_editor_property("default", 3500 if near_fade else 5000)
                end.set_editor_property("default", 5000 if near_fade else 8000)
                v.set_editor_property("start_cull_distance", start)
                v.set_editor_property("end_cull_distance", end)
                v.set_editor_property("random_rotation", True)
                v.set_editor_property("align_to_surface", True)
                v.set_editor_property("cast_dynamic_shadow", True)
                # Poly Haven grass tufts are small (~30 cm): grow the meadow to a lush 40-70 cm.
                v.set_editor_property("scale_x", unreal.FloatInterval(1.4, 2.2) if type_name == "Meadow" else unreal.FloatInterval(0.8, 1.3))
                entries.append(v)
        lgt.set_editor_property("grass_varieties", entries)
        unreal.EditorAssetLibrary.save_loaded_asset(lgt)
        out[type_name] = lgt
        log(f"grass type {type_name}: {len(entries)} varieties")
    return out


def build_landscape_material():
    """M_LandscapeReal: five height-blended Poly Haven layers (albedo fades to a variation set at 4x scale with distance,
    large-scale brightness variation against tiling), normal and roughness, and the landscape grass output (meadow on Grass, ferns and moss on Forest)."""
    m = fresh_asset("M_LandscapeReal", WORLD_DIR, unreal.Material, unreal.MaterialFactoryNew())
    depth = expr(m, unreal.MaterialExpressionPixelDepth, -2600, -600)
    near = expr(m, unreal.MaterialExpressionSubtract, -2400, -600, const_b=1500.0)
    MEL.connect_material_expressions(depth, "", near, "A")
    far = expr(m, unreal.MaterialExpressionDivide, -2250, -600, const_b=6000.0)
    MEL.connect_material_expressions(near, "", far, "A")
    fade = expr(m, unreal.MaterialExpressionSaturate, -2100, -600)
    MEL.connect_material_expressions(far, "", fade, "")
    albedo, normal, rough = (layer_blend(m, -600, y) for y in (-400, 0, 300))
    y = 0
    for name, (main, variation, tile) in LAYERS.items():
        uv_near = expr(m, unreal.MaterialExpressionLandscapeLayerCoords, -2400, y, mapping_scale=tile)
        uv_far = expr(m, unreal.MaterialExpressionLandscapeLayerCoords, -2400, y + 120, mapping_scale=tile * 4)
        a_near = sample(m, main, "A", uv_near, -2000, y)
        a_far = sample(m, variation, "A", uv_far, -2000, y + 150)
        mix = expr(m, unreal.MaterialExpressionLinearInterpolate, -1600, y)
        MEL.connect_material_expressions(a_near, "RGB", mix, "A")
        MEL.connect_material_expressions(a_far, "RGB", mix, "B")
        MEL.connect_material_expressions(fade, "", mix, "Alpha")
        n = sample(m, main, "N", uv_near, -2000, y + 300)
        r = sample(m, main, "R", uv_near, -2000, y + 450)
        d = sample(m, main, "D", uv_near, -2000, y + 600)
        MEL.connect_material_expressions(mix, "", albedo, f"Layer {name}")
        MEL.connect_material_expressions(n, "RGB", normal, f"Layer {name}")
        MEL.connect_material_expressions(r, "R", rough, f"Layer {name}")
        for blend in (albedo, normal, rough):
            MEL.connect_material_expressions(d, "R", blend, f"Height {name}")
        y += 800
    # Large-scale variation: a height map stretched over 80 m tiles, as a +-15% brightness swing.
    macro_uv = expr(m, unreal.MaterialExpressionLandscapeLayerCoords, -900, -900, mapping_scale=80.0)
    macro = sample(m, "rocky_terrain", "D", macro_uv, -700, -900)
    swing = expr(m, unreal.MaterialExpressionLinearInterpolate, -400, -800, const_a=0.85, const_b=1.15)
    MEL.connect_material_expressions(macro, "R", swing, "Alpha")
    base = expr(m, unreal.MaterialExpressionMultiply, -250, -400)
    MEL.connect_material_expressions(albedo, "", base, "A")
    MEL.connect_material_expressions(swing, "", base, "B")
    slab = expr(m, unreal.MaterialExpressionSubstrateShadingModels, -50, 0)
    MEL.connect_material_expressions(base, "", slab, "BaseColor")
    MEL.connect_material_expressions(rough, "", slab, "Roughness")
    MEL.connect_material_expressions(normal, "", slab, "Normal")
    MEL.connect_material_property(slab, "", unreal.MaterialProperty.MP_FRONT_MATERIAL)
    types = grass_types()
    grass = expr(m, unreal.MaterialExpressionLandscapeGrassOutput, -50, 900)
    inputs = []
    for type_name in GRASS_TYPES:
        gi = unreal.GrassInput()
        gi.set_editor_property("name", type_name)
        gi.set_editor_property("grass_type", types[type_name])
        inputs.append(gi)
    grass.set_editor_property("grass_types", inputs)
    for i, (type_name, (layer, _)) in enumerate(GRASS_TYPES.items()):
        weight = expr(m, unreal.MaterialExpressionLandscapeLayerSample, -400, 900 + i * 150, parameter_name=layer)
        MEL.connect_material_expressions(weight, "", grass, type_name)
    errors = MEL.recompile_material(m)
    if errors:
        raise RuntimeError(f"M_LandscapeReal failed to compile: {errors}")
    unreal.EditorAssetLibrary.save_loaded_asset(m)
    return m


def solid_material(name, colour, roughness=0.8):
    parent = unreal.load_asset("/Game/Shinobi/Materials/M_ShinobiSolid")
    mi = fresh_asset(name, WORLD_DIR, unreal.MaterialInstanceConstant, unreal.MaterialInstanceConstantFactoryNew())
    MEL.set_material_instance_parent(mi, parent)
    MEL.set_material_instance_vector_parameter_value(mi, "Color", unreal.LinearColor(*colour, 1))
    unreal.EditorAssetLibrary.save_loaded_asset(mi)
    return mi


def spawn_class(cls, location, yaw=0.0, pitch=0.0, label=None):
    actor = EAS.spawn_actor_from_class(cls, unreal.Vector(*location), unreal.Rotator(0, pitch, yaw))
    if label:
        actor.set_actor_label(label)
    return actor


def spawn_mesh(mesh_path, material, location, scale, yaw=0.0, label=None):
    actor = spawn_class(unreal.StaticMeshActor, location, yaw, label=label)
    actor.static_mesh_component.set_static_mesh(unreal.load_asset(mesh_path))
    actor.static_mesh_component.set_material(0, material)
    actor.set_actor_scale3d(unreal.Vector(*scale))
    return actor


def apply_mood(sun, fog):
    """Warm, low sun from the south-west; thin fog pooling in the valley (it thins with height)."""
    sun.set_actor_rotation(unreal.Rotator(0, -22, -35), False)
    light = sun.light_component
    light.set_editor_property("intensity", 7.0)
    light.set_editor_property("use_temperature", True)
    light.set_editor_property("temperature", 5600.0)
    component = fog.component
    component.set_editor_property("fog_density", 0.025)
    component.set_editor_property("fog_height_falloff", 0.12)
    component.set_editor_property("start_distance", 2500.0)
    component.set_editor_property("fog_inscattering_luminance", unreal.LinearColor(0.55, 0.45, 0.35, 1.0))


def stage_terrain(lay):
    meta = terrain_maps(regenerate=True)
    ensure_dir(WORLD_DIR)
    ensure_dir("/Game/Shinobi/Maps")
    level_editor = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if unreal.EditorAssetLibrary.does_asset_exist(MAP):
        unreal.EditorAssetLibrary.delete_asset(MAP)
    if not level_editor.new_level(MAP, True):
        raise RuntimeError(f"could not create World Partition map {MAP}")
    world = unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem).get_editor_world()

    weightmaps = {name: os.path.join(TERRAIN_DIR, f"weight_{name.lower()}.png") for name in LAYERS}
    landscape = unreal.ShinobiWorldBuilderLibrary.create_landscape(
        world, os.path.join(TERRAIN_DIR, "height.png"), build_landscape_material(), weightmaps, f"{WORLD_DIR}/LayerInfo", 4)
    if landscape is None:
        raise RuntimeError("landscape creation failed (see LogShinobiCoop)")

    # Light and atmosphere: a warm late-afternoon sun, sky, valley fog, clouds, the toon post-process.
    sun = spawn_class(unreal.DirectionalLight, (0, 0, uu(200)), label="Sun")
    sun.light_component.set_editor_property("atmosphere_sun_light", True)
    spawn_class(unreal.SkyAtmosphere, (0, 0, 0), label="SkyAtmosphere")
    sky = spawn_class(unreal.SkyLight, (0, 0, uu(50)), label="SkyLight")
    sky.light_component.set_editor_property("real_time_capture", True)
    fog = spawn_class(unreal.ExponentialHeightFog, (0, 0, uu(meta["water_level_m"])), label="Fog")
    apply_mood(sun, fog)
    spawn_class(unreal.VolumetricCloud, (0, 0, 0), label="Clouds")
    volume = spawn_class(unreal.PostProcessVolume, (0, 0, 0), label=TOON_VOLUME_LABEL)
    volume.set_editor_property("unbound", True)
    settings = volume.get_editor_property("settings")
    toon = unreal.load_asset("/Game/Shinobi/Materials/M_ToonPost")
    settings.set_editor_property("weighted_blendables", unreal.WeightedBlendables(array=[unreal.WeightedBlendable(weight=1.0, object=toon)]))
    volume.set_editor_property("settings", settings)

    # Player start in the village square (facing the north gate).
    vx, vy, _ = lay.areas["village"]
    spawn_class(unreal.PlayerStart, (uu(vx), uu(vy + 15), uu(meta["village_height_m"]) + 120), yaw=90, label="VillageStart")

    # River: one flat plane at the water level; the terrain hides it everywhere but the river bed.
    water = solid_material("MI_Water", (0.05, 0.22, 0.35), 0.1)
    plane = spawn_mesh("/Engine/BasicShapes/Plane.Plane", water, (0, 0, uu(meta["water_level_m"])), (lay.size_m + 100, lay.size_m + 100, 1), label="RiverWater")
    plane.static_mesh_component.set_collision_profile_name("NoCollision")  # wade through: the river bed is the floor
    plane.static_mesh_component.set_cast_shadow(False)

    # Invisible walls just inside the mountains; the kill-Z is handled by the world game mode (W4).
    wall_material = solid_material("MI_EdgeWall", (0.5, 0.5, 0.5))
    edge = 465.0
    for i, (x, y, sx, sy) in enumerate(((edge, 0, 1, 2 * edge), (-edge, 0, 1, 2 * edge), (0, edge, 2 * edge, 1), (0, -edge, 2 * edge, 1))):
        wall = spawn_mesh("/Engine/BasicShapes/Cube.Cube", wall_material, (uu(x), uu(y), uu(100)), (sx, sy, 400), label=f"EdgeWall{i}")
        wall.set_actor_hidden_in_game(True)
        wall.static_mesh_component.set_collision_profile_name("InvisibleWall")

    world_settings = world.get_world_settings()
    world_settings.set_editor_property("default_game_mode", unreal.load_class(None, "/Script/ShinobiCoop.ShinobiWorldGameMode"))
    world_settings.set_editor_property("kill_z", -5000.0)
    if not unreal.EditorLoadingAndSavingUtils.save_map(world, MAP):
        raise RuntimeError(f"failed to save {MAP}")
    unreal.EditorLoadingAndSavingUtils.save_dirty_packages(True, True)
    log(f"terrain: built {MAP} (water {meta['water_level_m']:.1f} m, village {meta['village_height_m']:.1f} m)")


DRESSING_TAG = "ShinobiDressing"


def load_map_fully():
    level_editor = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if not level_editor.load_level(MAP):
        raise RuntimeError(f"could not load {MAP} (run the terrain stage first)")
    world = unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem).get_editor_world()
    descs = unreal.WorldPartitionBlueprintLibrary.get_actor_descs()
    unreal.WorldPartitionBlueprintLibrary.load_actors([d.guid for d in descs])
    return world


def tag(actor, *extra):
    actor.set_editor_property("tags", [unreal.Name(DRESSING_TAG)] + [unreal.Name(t) for t in extra])
    if any(t in ("ShinobiCampSite", "Tour") for t in extra):
        # Gameplay markers (camps must work anywhere on the map) and tour points stay loaded, not streamed.
        actor.set_editor_property("is_spatially_loaded", False)
    return actor


def catalog_meshes():
    with open(os.path.join(HERE, "library_catalog.json"), encoding="utf-8") as f:
        catalog = json.load(f)
    cache = {}

    def mesh(key):
        if key not in cache:
            category, name = key.split("/", 1)
            entry = catalog.get(category, {}).get(name)
            cache[key] = unreal.load_asset(entry["mesh"]) if entry else None
            if cache[key] is None:
                unreal.log_warning(f"[build_world] missing library mesh {key}: placeholder cube used")
                cache[key] = unreal.load_asset("/Engine/BasicShapes/Cube.Cube")
        return cache[key]
    return mesh


def place(mesh_of, it, label=None, *tags):
    actor = EAS.spawn_actor_from_class(unreal.StaticMeshActor, unreal.Vector(it["x"], it["y"], it["z"]), unreal.Rotator(0, 0, it["yaw"]))
    actor.static_mesh_component.set_static_mesh(mesh_of(it["mesh"]))
    actor.set_actor_scale3d(unreal.Vector(it["scale"], it["scale"], it["scale"]))
    actor.static_mesh_component.set_mobility(unreal.ComponentMobility.STATIC)
    if label:
        actor.set_actor_label(label)
    return tag(actor, *tags)


def marker(x, y, z, label, *tags):
    point = EAS.spawn_actor_from_class(unreal.TargetPoint, unreal.Vector(x, y, z + 50), unreal.Rotator(0, 0, 0))
    point.set_actor_label(label)
    return tag(point, "ShinobiCampSite", *tags)


def stage_dress(lay):
    path = os.path.join(TERRAIN_DIR, "placements.json")
    subprocess.run(["python", os.path.join(HERE, "make_placements.py"), path], check=True)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    world = load_map_fully()
    old = [a for a in unreal.GameplayStatics.get_all_actors_of_class(world, unreal.Actor) if a.actor_has_tag(DRESSING_TAG)]
    for actor in old:
        EAS.destroy_actor(actor)
    mesh_of = catalog_meshes()

    for i, it in enumerate(data["buildings"]):
        tour = ["Tour", "Tour:Gate"] if it["mesh"] == "Arch/gate" else (["Tour", "Tour:Shrine"] if it["mesh"] == "Arch/shrine" else [])
        place(mesh_of, it, f"Village_{it['mesh'].split('/')[-1]}_{i:02d}", *tour)
    for i, it in enumerate(data["walls"]):
        place(mesh_of, it, f"VillageWall_{i:02d}")
    place(mesh_of, data["bridge"], "RiverBridge", "Tour", "Tour:Bridge")
    # Close-up tour points (sub-project #3b): ground, grass and forest detail.
    for name, p in data["tour_points"].items():
        point = EAS.spawn_actor_from_class(unreal.TargetPoint, unreal.Vector(p["x"], p["y"], p["z"] + 50), unreal.Rotator(0, 0, 0))
        point.set_actor_label(f"Tour_{name}")
        tag(point, "Tour", f"Tour:{name}")
    for camp in data["camps"]:
        for i, it in enumerate(camp["dressing"]):
            place(mesh_of, it, f"{camp['id']}_{it['mesh'].split('/')[-1]}_{i:02d}")
        marker(camp["x"], camp["y"], camp["z"], camp["id"], f"Camp:{camp['id']}", f"Difficulty:{camp['difficulty']}",
               f"Radius:{camp['r'] + 1500:.0f}",
               "Waves:" + ";".join(f"{w['ninjas']},{w['throwers']}" for w in camp["waves"]))
    boss = data["boss"]
    for i, it in enumerate(boss["dressing"]):
        place(mesh_of, it, f"BossRuin_{i:02d}")
    marker(boss["x"], boss["y"], boss["z"], "boss", "Boss", f"Radius:{boss['r'] + 1500:.0f}")
    for i, route in enumerate(data["villagers"]):
        first = route[0]
        point = EAS.spawn_actor_from_class(unreal.TargetPoint, unreal.Vector(first["x"], first["y"], first["z"] + 50), unreal.Rotator(0, 0, 0))
        point.set_actor_label(f"Villager_{i}")
        tag(point, "ShinobiVillager", "Route:" + "|".join(f"{p['x']:.0f},{p['y']:.0f},{p['z']:.0f}" for p in route))
        point.set_editor_property("is_spatially_loaded", False)

    instances = 0
    for chunk, species in data["scatter"].items():
        cx, cy = (int(v) for v in chunk.split("_"))
        centre = unreal.Vector(uu(-lay.size_m / 2 + (cx + 0.5) * 128), uu(-lay.size_m / 2 + (cy + 0.5) * 128), 0)
        actor = EAS.spawn_actor_from_class(unreal.ShinobiScatterActor, centre, unreal.Rotator(0, 0, 0))
        actor.set_actor_label(f"Nature_{chunk}")
        tag(actor)
        for key, entry in species.items():
            transforms = [unreal.Transform(unreal.Vector(x, y, z), unreal.Rotator(0, 0, yaw), unreal.Vector(sc, sc, sc))
                          for x, y, z, yaw, sc in entry["items"]]
            actor.add_instances(mesh_of(key), transforms, entry["cull"])
        instances += actor.get_instance_count()

    world.get_world_settings().set_editor_property("default_game_mode", unreal.load_class(None, "/Script/ShinobiCoop.ShinobiWorldGameMode"))
    if not unreal.EditorLoadingAndSavingUtils.save_map(world, MAP):
        raise RuntimeError(f"failed to save {MAP}")
    unreal.EditorLoadingAndSavingUtils.save_dirty_packages(True, True)
    log(f"dress: {len(data['buildings'])} buildings, {len(data['walls'])} walls, {len(data['camps'])} camps, "
        f"{instances} scattered instances in {len(data['scatter'])} chunks")


def import_ambience():
    subprocess.run(["python", os.path.join(HERE, "make_ambience.py")], check=True)
    source = os.path.join(PROJECT, "SourceArt", "Audio", "World")
    tasks = []
    for name in ("Amb_Forest", "Amb_River"):
        task = unreal.AssetImportTask()
